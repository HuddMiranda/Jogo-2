def grid(text):
    rows = [r for r in text.strip('\n').split('\n')]
    width = max(len(r) for r in rows)
    rows = [list(r.ljust(width, '.')) for r in rows]
    # Buracos transparentes presos dentro da silhueta viram contorno escuro.
    h = len(rows)
    outside = set()
    stack = [(x, y) for x in range(width) for y in (0, h - 1)] + [(x, y) for y in range(h) for x in (0, width - 1)]
    while stack:
        x, y = stack.pop()
        if (x, y) in outside or not (0 <= x < width and 0 <= y < h) or rows[y][x] != '.':
            continue
        outside.add((x, y))
        stack += [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]
    for y in range(h):
        for x in range(width):
            if rows[y][x] == '.' and (x, y) not in outside:
                rows[y][x] = 'O'
    return [''.join(r) for r in rows]


def render(rows, palette, scale=1):
    h, w = len(rows), len(rows[0])
    img = Image.new('RGBA', (w, h), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch != '.':
                hexc = palette[ch]
                img.putpixel((x, y), tuple(int(hexc[i:i + 2], 16) for i in (0, 2, 4)) + (255,))
    return img.resize((w * scale, h * scale), Image.NEAREST) if scale > 1 else img


def main():
    out = os.path.join(ROOT, 'art', 'handmade')
    os.makedirs(out, exist_ok=True)
    rows = grid(IDLE)
    for name, palette in PALETTES.items():
        render(rows, palette).save(os.path.join(out, f'vex_idle_{name}.png'))
    print('ok', len(rows[0]), 'x', len(rows))


if __name__ == '__main__':
    main()
